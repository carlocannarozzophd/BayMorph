"""High-level BayMorph workflow runner."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from baymorph.pipeline import (
    run_image_preparation,
    run_psf_candidate_selection,
    run_psf_construction,
    run_real_fit,
)


@dataclass
class BayMorphRunner:
    """Coordinate the high-level BayMorph analysis workflows.

    Parameters
    ----------
    config : dict of str to Any
        BayMorph configuration dictionary.
    image_preparation_products : Any, optional
        Products generated by image preparation.
    psf_candidate_products : Any, optional
        Products generated by PSF candidate selection.
    psf_products : Any, optional
        Products generated by PSF construction.
    fit_result : Any, optional
        Bayesian fitting result.
    profile_bands : Any, optional
        Posterior radial-profile bands, if computed.
    """

    config: dict[str, Any]

    image_preparation_products: Any = None
    psf_candidate_products: Any = None
    psf_products: Any = None
    fit_result: Any = None
    profile_bands: Any = None

    @classmethod
    def from_config(
        cls,
        config: dict[str, Any],
    ) -> BayMorphRunner:
        """Create a runner from a configuration dictionary.

        Parameters
        ----------
        config : dict of str to Any
            BayMorph configuration dictionary.

        Returns
        -------
        BayMorphRunner
            Runner initialized with a shallow copy of the configuration.
        """
        return cls(
            config=dict(config),
        )

    @property
    def output_dir(self) -> Path | None:
        """Return the configured output directory, when available."""
        value = self.config.get("output_dir")

        if value is None:
            return None

        return Path(value)

    @property
    def image(self) -> Any:
        """Return the image-preparation products."""
        return self.image_preparation_products

    @property
    def psf_candidates(self) -> Any:
        """Return the selected PSF candidates."""
        return self.psf_candidate_products

    @property
    def psf(self) -> Any:
        """Return the constructed PSF products."""
        return self.psf_products

    @property
    def results(self) -> Any:
        """Return the Bayesian fitting results."""
        return self.fit_result

    @staticmethod
    def _separator() -> None:
        """Print a console separator."""
        print("────────────────────────────────────────────────────")

    @staticmethod
    def _status(message: str) -> None:
        """Print a completed-step status message."""
        print(f"✓ {message}")

    @staticmethod
    def _info(message: str) -> None:
        """Print an informational console message."""
        print(f"• {message}")

    def prepare_image(
        self,
        *,
        return_result: bool = False,
    ) -> Any | None:
        """Run image preparation.

        Parameters
        ----------
        return_result : bool, default=False
            If True, return the image-preparation products.

        Returns
        -------
        Any or None
            Image-preparation products if ``return_result`` is True,
            otherwise None.
        """
        self.image_preparation_products = run_image_preparation(
            self.config,
        )

        self._status("Image preparation completed")

        if return_result:
            return self.image_preparation_products

        return None

    def select_psf_candidates(
        self,
        *,
        return_result: bool = False,
    ) -> Any | None:
        """Run PSF candidate selection.

        Parameters
        ----------
        return_result : bool, default=False
            If True, return the selected PSF candidates.

        Returns
        -------
        Any or None
            Selected PSF candidates if ``return_result`` is True,
            otherwise None.
        """
        self.psf_candidate_products = run_psf_candidate_selection(
            self.config,
        )

        try:
            n_candidates = len(self.psf_candidate_products)
            self._status(f"{n_candidates} PSF candidates selected")
        except Exception:
            self._status("PSF candidates selected")

        if return_result:
            return self.psf_candidate_products

        return None

    def build_psf(
        self,
        *,
        return_result: bool = False,
    ) -> Any | None:
        """Build the empirical PSF.

        Parameters
        ----------
        return_result : bool, default=False
            If True, return the empirical PSF products.

        Returns
        -------
        Any or None
            Empirical PSF products if ``return_result`` is True,
            otherwise None.
        """
        self.psf_products = run_psf_construction(
            self.config,
        )

        self._status("Empirical PSF constructed")

        if return_result:
            return self.psf_products

        return None

    def fit(
        self,
        *,
        return_result: bool = False,
    ) -> Any | None:
        """Run Bayesian fitting.

        Parameters
        ----------
        return_result : bool, default=False
            If True, return the fitting result.

        Returns
        -------
        Any or None
            Fitting result if ``return_result`` is True, otherwise None.
        """
        self.fit_result = run_real_fit(
            self.config,
        )

        self.profile_bands = None

        self._status("Bayesian fitting completed")

        if return_result:
            return self.fit_result

        return None

    def corner(self) -> None:
        """Generate corner-plot diagnostics.

        Raises
        ------
        RuntimeError
            If fitting has not been run.
        """
        if self.fit_result is None:
            raise RuntimeError(
                "Run fit() before corner()."
            )

        from baymorph.pipeline import run_corner_diagnostics

        run_corner_diagnostics(
            self.config,
            self.fit_result,
        )

        self._status("Corner plots generated")

    def residual_maps(self) -> None:
        """Generate residual-map diagnostics.

        Raises
        ------
        RuntimeError
            If fitting has not been run.
        """
        if self.fit_result is None:
            raise RuntimeError(
                "Run fit() before residual_maps()."
            )

        from baymorph.pipeline import run_residual_map_diagnostics

        run_residual_map_diagnostics(
            self.config,
            self.fit_result,
        )

        self._status("Residual maps generated")

    def radial_profile(
        self,
        *,
        return_result: bool = False,
    ) -> Any | None:
        """Generate radial-profile diagnostics.

        Parameters
        ----------
        return_result : bool, default=False
            If True, return posterior radial-profile bands when available.

        Returns
        -------
        Any or None
            Posterior radial-profile bands if generated and
            ``return_result`` is True, otherwise None.

        Raises
        ------
        RuntimeError
            If fitting has not been run.
        """
        if self.fit_result is None:
            raise RuntimeError(
                "Run fit() before radial_profile()."
            )

        from baymorph.pipeline import run_radial_profile_diagnostics

        self.profile_bands = run_radial_profile_diagnostics(
            self.config,
            self.fit_result,
        )

        self._status("Radial profiles generated")

        if return_result:
            return self.profile_bands

        return None

    def diagnostics(self) -> None:
        """Generate all available fit diagnostics.

        Raises
        ------
        RuntimeError
            If fitting has not been run.
        """
        self.corner()
        self.residual_maps()
        self.radial_profile()

        self._status("All diagnostics generated")